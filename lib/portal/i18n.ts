/**
 * Translate a key to the given locale. `locale` only ever resolves against
 * the STATIC dictionary here ('en'/'it') — a third language's text comes
 * from `dynamicTranslations`, the map returned by loadTranslationsForLocale()
 * (lib/portal/translations-store.ts). Optional and additive: every existing
 * 2-arg call site keeps working unchanged, resolving 'en'/'it' exactly as
 * before. useLocale() merges this same way for Client Components; a Server
 * Component page passes its own awaited loadTranslationsForLocale() result
 * here directly, since it cannot use the hook. Falls back to the static
 * dictionary, then to the key itself, if a key is missing from the dynamic
 * map (e.g. the key hasn't been generated for that language yet).
 */
export function t(key: string, locale: Locale = 'en', dynamicTranslations?: Record<string, string>): string {
  return dynamicTranslations?.[key] ?? translations[locale]?.[key] ?? translations['en']?.[key] ?? key
}

/**
 * Read-only snapshot of the English dictionary — the translation source of
 * truth for the AI-generation pipeline (lib/portal/translation-generator.ts,
 * dev job 12cab351). A copy, not a live reference: callers must never be
 * able to mutate the module-private `translations` object through this.
 */
export function getEnglishDictionary(): Record<string, string> {
  return { ...translations['en'] }
}

/**
 * Get locale from Supabase user metadata.
 *
 * Validates against isValidLanguageCode() (lib/portal/language-codes.ts,
 * ~180 real ISO 639-1 codes) rather than SUPPORTED_LOCALES — the same check
 * the write path (app/api/portal/language/route.ts) already enforces, so a
 * value that made it into user_metadata was already valid when written.
 * SUPPORTED_LOCALES alone would silently reject a genuinely-selected third
 * language the moment it was read back, reverting the client to English on
 * their very next page load with no error and no explanation — exactly the
 * "picker lets you choose it, then the app quietly ignores it" bug this
 * exists to avoid.
 *
 * The `as Locale` below is a DELIBERATE, DOCUMENTED narrowing, not an
 * accident: Locale stays the narrow 'en'|'it' type (see the comment above
 * SUPPORTED_LOCALES for why it is not widened), but this function can
 * genuinely return any valid ISO code once the language picker itself is
 * extended (a later milestone of dev job 12cab351 — not live yet, no
 * behavior change today). This is safe ONLY because the AI-architect review
 * of this same job confirmed no code anywhere treats Locale as an
 * exhaustive switch; every consumer either does `locale === 'it' ? a : b`
 * (which safely defaults to the English branch for any other string) or
 * looks a key up in a dictionary with its own independent English fallback
 * (t() above). A future consumer that DOES need to exhaustively switch on
 * Locale must use isValidLanguageCode()/LANGUAGE_NAMES instead of relying on
 * this type to enumerate every possibility.
 */
export function getLocale(user: { user_metadata?: Record<string, unknown> } | null): Locale {
  const lang = user?.user_metadata?.portal_language
  if (typeof lang === 'string' && isValidLanguageCode(lang)) {
    return lang.toLowerCase() as Locale
  }
  return 'en'
}
